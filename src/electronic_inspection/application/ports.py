from pathlib import Path
from typing import Protocol


class PackagePort(Protocol):
    def download_package(self, package_path: Path) -> None: ...


class ProvisioningCryptoPort(Protocol):
    def encrypt_level_1_key(self, key: bytes) -> bytes: ...
    def encrypt_level_11_key(self, key: bytes) -> bytes: ...
    def encrypt_certificate(self, certificate: bytes) -> bytes: ...


class SecurityAccessPort(Protocol):
    def calculate_key(self, level: int, seed: bytes) -> bytes: ...


class MdcPort(Protocol):
    def reboot(self) -> None: ...
    def wait_until_reachable(self, timeout: float) -> None: ...
    def collect_logs(self, local_path: Path) -> None: ...


class CanfdPort(Protocol):
    def start_wakeup(self) -> None: ...
    def stop_wakeup(self) -> None: ...


class UdsPort(Protocol):
    def diagnostic_session_control(self, session_type: int) -> bytes: ...
    def ecu_reset(self, reset_type: int) -> bytes: ...
    def read_data_by_identifier(self, identifier: int) -> bytes: ...
    def write_data_by_identifier(self, identifier: int, data: bytes) -> bytes: ...
    def read_dtc_information(
        self, sub_function: int, status_mask: int = 0xFF
    ) -> bytes: ...
    def clear_diagnostic_information(self, group_of_dtc: bytes) -> bytes: ...
    def request_security_seed(self, level: int) -> bytes: ...
    def send_security_key(self, level: int, key: bytes) -> bytes: ...
    def routine_control(
        self, control_type: int, routine_id: int, data: bytes = b""
    ) -> bytes: ...
    def control_dtc_setting(self, setting: int) -> bytes: ...
    def tester_present(self, sub_function: int = 0x00) -> bytes: ...
    def request_download(
        self,
        memory_address: int,
        memory_size: int,
        data_format_identifier: int = 0x00,
    ) -> bytes: ...
    def request_upload(
        self,
        memory_address: int,
        memory_size: int,
        data_format_identifier: int = 0x00,
    ) -> bytes: ...
    def transfer_data(
        self, block_sequence_counter: int, data: bytes = b""
    ) -> bytes: ...
    def request_transfer_exit(self, data: bytes = b"") -> bytes: ...
    def request_file_transfer(
        self, mode_of_operation: int, file_name: str, data_format_identifier: int = 0x00
    ) -> bytes: ...
